'use strict';
/* Slopitaire soundtrack renderer: pre-renders every music track, once per combo tier, into audio/music/ as Opus and
 * writes js/audio/music-files.js. Runs the game's own audio code in Chromium's Web Audio engine (Electron), so the
 * files sound like the live synth. See README.md.
 *
 *   npm run music                     render what is missing or out of date
 *   npm run music -- status           show what is up to date
 *   npm run music -- --force pulse    re-render one track (or several, space or comma separated)
 */
const { app, BrowserWindow, ipcMain } = require('electron');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn, spawnSync } = require('node:child_process');

const TOOL_VERSION = 1;
const ROOT = path.resolve(__dirname, '..', '..');
const OUT_DIR = 'audio/music'; // relative to ROOT, and the URL the game fetches from
const MANIFEST = path.join(ROOT, 'js', 'audio', 'music-files.js');
const CONFIG = path.join(__dirname, 'music.json');
// everything that changes what a render sounds like
const INPUTS = [
  'js/core/util.js', 'js/audio/tracks.js', 'js/audio/synth.js', 'js/audio/score.js',
  'tools/music/render.js', // (bump TOOL_VERSION when the encoder settings in this file change)
];
const TIERS = 5;
const STEPS_PER_LOOP = 64;

// ---------- command line ----------

function usage() {
  return `usage: npm run music -- [render|status] [track ...] [options]

  render (default)   render missing or out-of-date tracks
  status             list each track's state without rendering

  track ...          limit to these tracks (space or comma separated)
  --force            render even if up to date
  --kbps N           Opus bitrate (default ${readConfig().kbps})
  --min-seconds N    shortest loop to render; loops are a multiple of 4 bars x 4 (default ${readConfig().minSeconds})
  --jobs N           parallel render windows (default: half the CPU cores, at most 8)
  --prune            delete audio/music folders of tracks that no longer exist
`;
}

function parseArgs(argv) {
  const o = { cmd: 'render', tracks: [], force: false, prune: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const val = () => {
      const v = argv[++i];
      if (v == null) throw new Error(`${a} needs a value`);
      return v;
    };
    if (a === 'render' || a === 'status') o.cmd = a;
    else if (a === '--help' || a === '-h') o.cmd = 'help';
    else if (a === '--force') o.force = true;
    else if (a === '--prune') o.prune = true;
    else if (a === '--kbps') o.kbps = Number(val());
    else if (a === '--min-seconds') o.minSeconds = Number(val());
    else if (a === '--jobs') o.jobs = Number(val());
    else if (a.startsWith('--')) throw new Error(`unknown option ${a}`);
    else o.tracks.push(...a.split(',').filter(Boolean));
  }
  return o;
}

// electron [chromium switches] tools/music/main.js [args]: keep only what follows this script
function scriptArgs() {
  const i = process.argv.findIndex((a) => path.resolve(a) === __filename || path.resolve(a) === __dirname);
  return process.argv.slice(i >= 0 ? i + 1 : 2);
}

// ---------- files ----------

function readConfig() {
  return JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
}

function readManifest() {
  try {
    const src = fs.readFileSync(MANIFEST, 'utf8');
    const json = src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1);
    return JSON.parse(json);
  } catch {
    return { dir: OUT_DIR, format: 'opus', sampleRate: 48000, tracks: {} };
  }
}

function writeManifest(m) {
  const sorted = { ...m, tracks: Object.fromEntries(Object.keys(m.tracks).sort().map((k) => [k, m.tracks[k]])) };
  const body = JSON.stringify(sorted, (k, v) => (k === 'kicks' ? `@@${JSON.stringify(v)}@@` : v), 2)
    .replace(/"@@(.*?)@@"/g, (_, s) => JSON.parse(`"${s}"`)); // keep each kick list on one line
  const text = `/* Generated by tools/music (npm run music). Do not edit by hand.
 * Pre-rendered soundtrack: one Opus loop per track and combo tier (0..4), all the same length and starting on the same
 * downbeat, so js/audio/sound.js can crossfade between tiers in sync.
 * loop: loop length (s) · gain: undoes the render's peak normalization · kicks: kick-drum times in the loop (beat
 * telemetry) · tiers[n].v: content hash, appended as ?v= so caches pick up re-rendered files · src: hash of the inputs. */
window.MUSIC_FILES = ${body};
`;
  writeAtomic(MANIFEST, text);
}

function writeAtomic(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, data);
  fs.renameSync(tmp, file);
}

const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');
const fileHash = (file) => sha(fs.readFileSync(file)).slice(0, 10);

function inputsHash() {
  const h = crypto.createHash('sha256').update(`v${TOOL_VERSION}\n`);
  for (const f of INPUTS) h.update(`${f}\n`).update(fs.readFileSync(path.join(ROOT, f)));
  return h.digest('hex');
}

// ---------- plan ----------

// A loop is a whole number of 4-loop cycles (the chill tracks alternate phrases over 4 loops, the electronic ones
// over 2), and at least minSeconds long so the random melody variations don't repeat too soon.
function planTrack(name, info, cfg, inputs) {
  const over = (cfg.tracks && cfg.tracks[name]) || {};
  const loopSec4 = (4 * STEPS_PER_LOOP * 60) / info.bpm / 4;
  let loops = over.loops || 4 * Math.max(1, Math.ceil(cfg.minSeconds / loopSec4 - 1e-9));
  if (loops % 4) loops += 4 - (loops % 4);
  const settings = {
    name, loops, kbps: cfg.kbps, sampleRate: cfg.sampleRate, seed: cfg.seed, peakDb: cfg.peakDb, format: cfg.format,
  };
  return { name, bpm: info.bpm, loops, settings, src: sha(inputs + JSON.stringify(settings)).slice(0, 12) };
}

function trackState(plan, entry) {
  if (!entry) return 'missing';
  for (let k = 0; k < TIERS; k++) {
    const t = entry.tiers && entry.tiers[k];
    const file = t && path.join(ROOT, OUT_DIR, t.file);
    if (!t || !fs.existsSync(file)) return 'missing';
    if (fileHash(file) !== t.v) return 'changed on disk';
  }
  return entry.src === plan.src ? 'up to date' : 'out of date';
}

// ---------- encoder ----------

function findFfmpeg() {
  const bin = process.env.FFMPEG || 'ffmpeg';
  const r = spawnSync(bin, ['-hide_banner', '-encoders'], { encoding: 'utf8' });
  if (r.error || r.status !== 0) throw new Error(`ffmpeg not found (${bin}). Install it, or set FFMPEG=/path/to/ffmpeg.`);
  if (!/libopus/.test(r.stdout)) throw new Error(`${bin} was built without libopus.`);
  return bin;
}

function encodeOpus(ffmpeg, pcm, sampleRate, kbps, outFile) {
  return new Promise((resolve, reject) => {
    const tmp = `${outFile}.${process.pid}.tmp`;
    const p = spawn(ffmpeg, [
      '-hide_banner', '-loglevel', 'error', '-y',
      '-f', 'f32le', '-ar', String(sampleRate), '-ac', '1', '-i', 'pipe:0',
      '-c:a', 'libopus', '-b:a', `${kbps}k`, '-vbr', 'on', '-compression_level', '10', '-application', 'audio',
      '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', '-f', 'ogg', tmp,
    ], { stdio: ['pipe', 'ignore', 'pipe'] });
    let err = '';
    p.stderr.on('data', (d) => { err += d; });
    p.on('error', reject);
    p.on('close', (code) => {
      if (code !== 0) {
        fs.rmSync(tmp, { force: true });
        reject(new Error(`ffmpeg exited ${code}: ${err.trim()}`));
        return;
      }
      fs.renameSync(tmp, outFile);
      resolve();
    });
    p.stdin.on('error', () => {}); // reported through 'close'
    p.stdin.end(Buffer.from(pcm.buffer, pcm.byteOffset, pcm.byteLength));
  });
}

// ---------- render windows ----------

class Worker {
  constructor() {
    this.win = new BrowserWindow({
      show: false,
      webPreferences: { preload: path.join(__dirname, 'preload.js'), backgroundThrottling: false },
    });
    this.pending = new Map();
    this.ready = new Promise((res) => { this.onReady = res; });
    this.win.loadFile(path.join(__dirname, 'render.html'));
  }

  run(kind, payload) {
    const id = Worker.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.win.webContents.send('job', id, kind, payload);
    });
  }
}
Worker.nextId = 1;

function wireWorkers(workers) {
  const byContents = (e) => workers.find((w) => w.win.webContents === e.sender);
  ipcMain.on('ready', (e) => { const w = byContents(e); if (w) w.onReady(); });
  ipcMain.on('done', (e, id, result) => {
    const w = byContents(e), p = w && w.pending.get(id);
    if (p) { w.pending.delete(id); p.resolve(result); }
  });
  ipcMain.on('fail', (e, id, message) => {
    const w = byContents(e), p = w && w.pending.get(id);
    if (p) { w.pending.delete(id); p.reject(new Error(message)); }
  });
}

// run tasks on whichever window is free
async function pool(workers, tasks) {
  const queue = tasks.slice();
  await Promise.all(workers.map(async (w) => {
    await w.ready;
    while (queue.length) await queue.shift()(w);
  }));
}

// ---------- main ----------

const fmtS = (s) => `${s.toFixed(1)}s`;
const fmtMB = (n) => `${(n / 1048576).toFixed(2)} MB`;

async function main() {
  const opts = parseArgs(scriptArgs());
  if (opts.cmd === 'help') { process.stdout.write(usage()); return 0; }

  const cfg = readConfig();
  if (opts.kbps) cfg.kbps = opts.kbps;
  if (opts.minSeconds) cfg.minSeconds = opts.minSeconds;
  if (!(cfg.kbps >= 6 && cfg.kbps <= 256)) throw new Error('--kbps must be between 6 and 256');
  if (cfg.format !== 'opus') throw new Error(`unsupported format ${cfg.format} (only opus)`);

  const jobs = Math.max(1, Math.min(opts.jobs || Math.min(8, Math.max(1, os.cpus().length >> 1)), 32));
  const workers = [new Worker()];
  wireWorkers(workers);
  await workers[0].ready;
  const info = await workers[0].run('tracks', null);
  const names = Object.keys(info);
  for (const t of opts.tracks) if (!info[t]) throw new Error(`unknown track "${t}" (tracks: ${names.join(', ')})`);
  const selected = opts.tracks.length ? opts.tracks : names;

  const inputs = inputsHash();
  const manifest = readManifest();
  manifest.dir = OUT_DIR;
  manifest.format = cfg.format;
  manifest.sampleRate = cfg.sampleRate;
  const plans = selected.map((n) => planTrack(n, info[n], cfg, inputs));

  const todo = [];
  for (const p of plans) {
    const state = trackState(p, manifest.tracks[p.name]);
    const e = manifest.tracks[p.name];
    const size = e && state !== 'missing'
      ? e.tiers.reduce((s, t) => s + fs.statSync(path.join(ROOT, OUT_DIR, t.file)).size, 0) : 0;
    console.log(`${p.name.padEnd(9)} ${state.padEnd(16)} ${String(p.loops).padStart(2)} loops · ${fmtS(p.loops * STEPS_PER_LOOP * 15 / p.bpm)}${size ? ` · ${fmtMB(size)}` : ''}`);
    if (opts.force || state !== 'up to date') todo.push(p);
  }
  const stray = fs.existsSync(path.join(ROOT, OUT_DIR))
    ? fs.readdirSync(path.join(ROOT, OUT_DIR)).filter((d) => !info[d]) : [];
  for (const d of stray) {
    if (opts.prune && opts.cmd === 'render') {
      fs.rmSync(path.join(ROOT, OUT_DIR, d), { recursive: true, force: true });
      console.log(`pruned ${OUT_DIR}/${d}`);
    } else console.log(`${OUT_DIR}/${d} belongs to no track (--prune deletes it)`);
  }
  for (const name of Object.keys(manifest.tracks)) if (!info[name]) delete manifest.tracks[name];

  if (opts.cmd === 'status' || !todo.length) {
    if (opts.cmd === 'render') {
      if (stray.length && opts.prune) writeManifest(manifest);
      console.log('nothing to render');
    }
    return 0;
  }

  const ffmpeg = findFfmpeg();
  for (let i = 1; i < Math.min(jobs, todo.length * TIERS); i++) workers.push(new Worker());
  console.log(`\nrendering ${todo.length} track(s) × ${TIERS} tiers on ${workers.length} window(s), Opus ${cfg.kbps} kbps`);

  const t0 = Date.now();
  const results = new Map(todo.map((p) => [p.name, new Array(TIERS)]));
  const tasks = [];
  for (const p of todo) {
    for (let tier = 0; tier < TIERS; tier++) {
      tasks.push(async (w) => {
        const r = await w.run('render', {
          name: p.name, tier, loops: p.loops, sampleRate: cfg.sampleRate, seed: cfg.seed,
        });
        results.get(p.name)[tier] = r;
        console.log(`  ${p.name} tier ${tier}: ${fmtS(r.loop)} rendered in ${fmtS(r.ms / 1000)}`);
      });
    }
  }
  await pool(workers, tasks);

  let failed = 0;
  const finish = [];
  for (const p of todo) {
    finish.push(async (w) => {
      const tiers = results.get(p.name);
      // one gain for all five tiers, so crossfades stay level; the game multiplies it back in
      const peak = Math.max(...tiers.map((r) => r.peak));
      const target = Math.pow(10, cfg.peakDb / 20);
      const scale = peak > 0 ? target / peak : 1;
      const dir = path.join(ROOT, OUT_DIR, p.name);
      fs.mkdirSync(dir, { recursive: true });
      const entry = {
        bpm: p.bpm, loops: p.loops, loop: Number(tiers[0].loop.toFixed(6)),
        gain: Number((1 / scale).toFixed(6)), src: p.src,
        kicks: tiers[0].kicks.map((t) => Number(t.toFixed(5))), tiers: [],
      };
      const notes = [];
      for (let k = 0; k < TIERS; k++) {
        const pcm = tiers[k].pcm;
        for (let i = 0; i < pcm.length; i++) pcm[i] *= scale;
        const rel = `${p.name}/${k}.opus`, file = path.join(ROOT, OUT_DIR, rel);
        await encodeOpus(ffmpeg, pcm, cfg.sampleRate, cfg.kbps, file);
        const bytes = fs.readFileSync(file);
        const v = await w.run('verify', { bytes, ref: pcm, sampleRate: cfg.sampleRate });
        const ok = v.lag === 0 && Math.abs(v.decodedLength - v.expectedLength) <= 1 && v.snrDb > 12;
        if (!ok) failed++;
        notes.push(`tier ${k} ${(bytes.length / 1024).toFixed(0)} KB, SNR ${v.snrDb.toFixed(1)} dB`
          + (v.lag ? `, OFFSET ${v.lag} samples` : '')
          + (v.decodedLength !== v.expectedLength ? `, decodes to ${v.decodedLength - v.expectedLength > 0 ? '+' : ''}${v.decodedLength - v.expectedLength} samples` : '')
          + (ok ? '' : '  <-- CHECK FAILED'));
        entry.tiers.push({ file: rel, v: sha(bytes).slice(0, 10) });
        tiers[k].pcm = null;
      }
      manifest.tracks[p.name] = entry;
      writeManifest(manifest); // after every track, so an interrupted run keeps what finished
      console.log(`${p.name}: gain ${entry.gain.toFixed(3)}, ${entry.kicks.length} kicks\n    ${notes.join('\n    ')}`);
    });
  }
  console.log('');
  await pool(workers, finish);

  console.log(`\ndone in ${fmtS((Date.now() - t0) / 1000)} → ${OUT_DIR}/, ${path.relative(ROOT, MANIFEST)}`);
  if (failed) console.error(`${failed} file(s) failed the decode check (see above)`);
  return failed ? 1 : 0;
}

// Linux without a display (CI, ssh): Chromium's headless platform needs no X or Wayland
if (process.platform === 'linux' && !process.env.DISPLAY && !process.env.WAYLAND_DISPLAY) {
  app.commandLine.appendSwitch('ozone-platform', 'headless');
}
app.disableHardwareAcceleration();
app.setName('slopitaire-music');
app.setPath('userData', path.join(os.tmpdir(), 'slopitaire-music-renderer'));
app.on('window-all-closed', () => {});

app.whenReady()
  .then(main)
  .then((code) => app.exit(code), (err) => {
    console.error(`error: ${err.message}`);
    app.exit(1);
  });
