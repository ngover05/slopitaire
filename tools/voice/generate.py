def cmd_bench(args):
    """Measure real throughput for a range of worker counts and remember the best for this machine."""
    import tempfile
    lines, cfg = load_lines(), load_config()
    rows = [r for r in compute_state(lines, cfg, {}, None, LANGS) if r['settings']]
    if not rows:
        die('configure at least one voice in voices.json first')
    devs = torch_devices()
    targets = [d['device'] for d in devs] if args.device in (None, 'auto') and devs else [args.device or 'cpu']
    phys, ram_cap = physical_cores(), max(1, int((available_ram_gb() - 1.0) / RAM_PER_WORKER_GB))
    best = {}
    with tempfile.TemporaryDirectory(prefix='voicebench-') as tmp:
        for target in targets:
            d = next((x for x in devs if x['device'] == target), None)
            if target == 'cpu':
                cap = min(phys, ram_cap)
            else:
                vram = (d or {}).get('free_gb') or 8
                cap = min(MAX_WORKERS_PER_GPU, int((vram - 0.5) / VRAM_PER_WORKER_GB), ram_cap, logical_cores())
            counts = sorted({c for c in (1, 2, 3, 4, 6, 8, 12, 16) if c <= max(1, cap)})
            log(f'benchmarking {target} with {counts} worker(s)')
            results = []
            for n in counts:
                # Same lines each round, a mix of both languages, enough to keep every worker busy several times.
                sample = []
                for r in rows:
                    sample += [(r, cid) for cid in sorted(r['want'])[:2]]
                per = max(args.clips, n * 8)
                sample = (sample * (per // max(1, len(sample)) + 1))[:per]
                jobs = []
                for k, (r, cid) in enumerate(sample):
                    s = r['settings']
                    jobs.append({'key': f'b{k}', 'text': r['want'][cid]['text'], 'voice': s['voice'],
                                 'speed': s['speed'], 'lang_code': s['lang_code'], 'post': s['post'],
                                 'kbps': s['output']['kbps'],
                                 'out': str(Path(tmp) / f'{n}-{k}{s["output"]["ext"]}')})
                threads = args.threads or (max(1, phys // n) if target == 'cpu'
                                           else max(1, min(4, (logical_cores() - 1) // n)))
                group = [{'device': target, 'workers': n, 'threads': threads, 'label': target}]
                stamps = []
                failures, el = run_jobs(jobs, group, cfg.get('model', 'hexgrad/Kokoro-82M'), quiet=True, warm=True,
                                        stamps=stamps)
                if failures:
                    log(f'  {n:>2} worker(s): failed ({failures[0][1]}) — stopping here')
                    break
                # Steady state only: process start-up and model loading would otherwise dominate a short round.
                skip = min(len(stamps) - 2, n * 2)
                rate = (len(stamps) - 1 - skip) / max(1e-6, stamps[-1] - stamps[skip])
                results.append((rate, n, threads))
                log(f'  {n:>2} worker(s) x {threads} thread(s): {rate:5.2f} clips/s')
                if len(results) >= 2 and rate < results[-2][0] * 1.03:
                    break  # stopped scaling
            if results:
                rate, n, threads = max(results)
                best[target] = n
                log(f'  -> {target}: {n} worker(s) ({rate:.2f} clips/s)')
    old = load_json(PROFILE_PATH, {})
    if old.get('fingerprint') == hw_fingerprint(devs):  # benchmarking one device keeps the others' results
        best = {**old.get('workers_per_device', {}), **best}
    profile = {'fingerprint': hw_fingerprint(devs), 'workers_per_device': best,
               'when': time.strftime('%Y-%m-%d %H:%M'), 'cpu': cpu_name(),
               'devices': [d['name'] for d in devs]}
    save_json(PROFILE_PATH, profile)
    log(f'saved {PROFILE_PATH.relative_to(ROOT)}; generate will use it on this machine')


