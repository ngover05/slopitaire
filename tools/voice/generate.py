def _load_audio(path: Path):
    import numpy as np
    import soundfile as sf
    a, sr = sf.read(str(path), dtype='float32', always_2d=False)
    if a.ndim > 1:
        a = a.mean(axis=1)
    if sr != SAMPLE_RATE:
        n = int(len(a) * SAMPLE_RATE / sr)
        a = np.interp(np.linspace(0, len(a) - 1, n), np.arange(len(a)), a).astype(np.float32)
    return a


def _logmel(a):
    import numpy as np
    n_fft, hop = 1024, 256
    a = a / (np.abs(a).max() or 1)
    frames = np.lib.stride_tricks.sliding_window_view(np.pad(a, (n_fft // 2,)), n_fft)[::hop]
    spec = np.abs(np.fft.rfft(frames * np.hanning(n_fft), axis=1)) ** 2
    # 40 triangular-ish bands on a log-frequency axis are plenty to tell voices apart
    edges = np.geomspace(2, spec.shape[1] - 1, 42).astype(int)
    bands = np.stack([spec[:, edges[i]:max(edges[i] + 1, edges[i + 2])].mean(axis=1) for i in range(40)], axis=1)
    return np.log(bands + 1e-8)


def _trim(a, db=-40):
    import numpy as np
    thr = 10 ** (db / 20) * (np.abs(a).max() or 1)
    idx = np.flatnonzero(np.abs(a) > thr)
    return a[idx[0]: idx[-1] + 1] if idx.size else a


def _distance(a, b):
    """Spectral distance after trimming silence and stretching b's frames onto a's timeline."""
    import numpy as np
    A, B = _logmel(_trim(a)), _logmel(_trim(b))
    idx = np.linspace(0, len(B) - 1, len(A)).round().astype(int)
    return float(np.mean(np.abs(A - B[idx])))


def cmd_match(args):
    """Find which Kokoro voice + speed produced the existing clips, so new lines sound the same."""
    from huggingface_hub import list_repo_files
    lines, cfg = load_lines(), load_config()
    model_id = cfg.get('model', 'hexgrad/Kokoro-82M')
    all_voices = sorted(Path(f).stem for f in list_repo_files(model_id) if f.startswith('voices/') and f.endswith('.pt'))
    devs = torch_devices()
    device = args.device if args.device and args.device != 'auto' else (devs[0]['device'] if devs else 'cpu')
    ensure_assets(model_id, all_voices=True)
    _worker_init(device, physical_cores(), model_id, [])
    langs = args.lang or LANGS
    suggestions = {}
    for char, data in lines.items():
        if args.char and char not in args.char:
            continue
        for lang in langs:
            def existing(cid):
                return next((p for f in FORMATS.values() if (p := clip_path(char, lang, cid, f['ext'])).exists()), None)
            entries = [e for e in data[lang] if existing(e['id'])]
            entries = sorted(entries, key=lambda e: abs(len(e['text']) - 30))[:args.samples]
            if not entries:
                continue
            refs = [(e, _load_audio(existing(e['id']))) for e in entries]
            if lang == 'ja':
                cands = [v for v in all_voices if v.startswith('j')]
            else:
                cands = [v for v in all_voices if v[:1] in 'ab']
            if not args.all_voices:
                cands = [v for v in cands if v[1] == 'f'] or cands
            total_ref = max(1, sum(len(_trim(r)) for _, r in refs))

            def score(voices):
                lc = 'j' if lang == 'ja' else ('b' if voices[0][0].startswith('b') else 'a')
                # speed from the duration ratio at 1.0, then compare spectra at that speed
                base = sum(len(_trim(_synth(lc, voices, 1.0, e['text']))) for e, _ in refs)
                speed = round(min(1.6, max(0.6, base / total_ref)) / 0.05) * 0.05
                dist = sum(_distance(r, _synth(lc, voices, speed, e['text'])) for e, r in refs) / len(refs)
                return dist, voices, round(speed, 2)

            def fmt(voices):
                return ','.join(n if w == 1 else f'{n}:{w:g}' for n, w in voices)

            scored = sorted((score([(v, 1.0)]) for v in cands), key=lambda t: t[0])
            log(f'{char}/{lang}: ' + ', '.join(f'{fmt(v)}@{sp:g} ({d:.3f})' for d, v, sp in scored[:4]))
            best = scored[0]
            if args.blends and best[0] > args.exact:
                # Not a single stock voice: try two-voice blends of the closest few, coarse then fine weights.
                top = [v[0][0] for _, v, _ in scored[:args.blends]]
                pairs = [(a, b) for i, a in enumerate(top) for b in top[i + 1:]]
                blends = [score([(a, w), (b, round(1 - w, 2))]) for a, b in pairs for w in (0.25, 0.5, 0.75)]
                blends.sort(key=lambda t: t[0])
                (a, wa), (b, _) = blends[0][1]
                fine = [score([(a, w), (b, round(1 - w, 2))]) for w in
                        sorted({round(min(0.95, max(0.05, wa + d)), 2) for d in (-0.15, -0.1, -0.05, 0.05, 0.1, 0.15)})]
                blends = sorted(blends + fine, key=lambda t: t[0])
                log(f'{"":>{len(char) + len(lang) + 2}}blends: ' +
                    ', '.join(f'{fmt(v)}@{sp:g} ({d:.3f})' for d, v, sp in blends[:3]))
                if blends[0][0] < best[0]:
                    best = blends[0]
            d, voices, speed = best
            verdict = 'exact' if d <= args.exact else 'close' if d <= args.exact * 2.5 else 'approximate'
            suggestions.setdefault(char, {})[lang] = {'voice': fmt(voices), 'speed': speed,
                                                      'distance': round(d, 4), 'match': verdict}
    print(json.dumps(suggestions, indent=1))


