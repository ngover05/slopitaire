# ------------------------------------------------------------------------------------- system probes

def physical_cores() -> int:
    logical = len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else (os.cpu_count() or 1)
    try:
        if sys.platform.startswith('linux'):
            cores = set()
            phys = core = None
            with open('/proc/cpuinfo') as f:
                for line in f:
                    if line.startswith('physical id'):
                        phys = line.split(':')[1].strip()
                    elif line.startswith('core id'):
                        core = line.split(':')[1].strip()
                    elif not line.strip():
                        if core is not None:
                            cores.add((phys, core))
                        phys = core = None
            if cores:
                return max(1, min(len(cores), logical))
        elif sys.platform == 'darwin':
            out = subprocess.run(['sysctl', '-n', 'hw.physicalcpu'], capture_output=True, text=True).stdout
            return max(1, int(out.strip()))
    except Exception:
        pass
    return max(1, logical // 2 if logical >= 4 else logical)


def logical_cores() -> int:
    return len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else (os.cpu_count() or 1)


def available_ram_gb() -> float:
    try:
        if sys.platform.startswith('linux'):
            with open('/proc/meminfo') as f:
                info = {l.split(':')[0]: int(l.split()[1]) for l in f if ':' in l}
            return info.get('MemAvailable', info.get('MemFree', 0)) / 2**20
        if sys.platform == 'darwin':
            out = subprocess.run(['sysctl', '-n', 'hw.memsize'], capture_output=True, text=True).stdout
            return int(out) / 2**30 * 0.6  # no cheap "available" on macOS; assume ~60% usable
        if os.name == 'nt':
            import ctypes

            class MS(ctypes.Structure):
                _fields_ = [('l', ctypes.c_ulong), ('load', ctypes.c_ulong)] + \
                           [(n, ctypes.c_ulonglong) for n in ('tp', 'ap', 'tf', 'af', 'tv', 'av', 'ae')]
            ms = MS()
            ms.l = ctypes.sizeof(MS)
            ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(ms))
            return ms.ap / 2**30
    except Exception:
        pass
    return 4.0


def cpu_name() -> str:
    try:
        if sys.platform.startswith('linux'):
            with open('/proc/cpuinfo') as f:
                for line in f:
                    if line.startswith('model name'):
                        return line.split(':', 1)[1].strip()
        if sys.platform == 'darwin':
            return subprocess.run(['sysctl', '-n', 'machdep.cpu.brand_string'],
                                  capture_output=True, text=True).stdout.strip()
    except Exception:
        pass
    return platform.processor() or platform.machine()


def run_quiet(cmd) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return ''


def detect_accelerator_without_torch() -> tuple[str, str]:
    """('cuda'|'rocm'|'mps'|'cpu', version-or-detail) using only system tools — used by `setup`."""
    if sys.platform == 'darwin':
        return ('mps', platform.machine()) if platform.machine() == 'arm64' else ('cpu', 'intel mac')
    if shutil.which('nvidia-smi'):
        out = run_quiet(['nvidia-smi'])
        m = re.search(r'CUDA Version:\s*([\d.]+)', out)
        if m:
            return 'cuda', m.group(1)
    if sys.platform.startswith('linux'):
        ver = ''
        for p in sorted(Path('/opt').glob('rocm*/.info/version'), reverse=True):
            ver = p.read_text().strip()
            break
        has_amd = 'gfx' in run_quiet(['rocminfo']) or Path('/dev/kfd').exists()
        if ver and has_amd:
            return 'rocm', ver
    return 'cpu', ''


# -------------------------------------------------------------------------------------------- setup

TORCH_INDEX = 'https://download.pytorch.org/whl/'


def url_exists(url: str) -> bool:
    import urllib.request
    try:
        with urllib.request.urlopen(urllib.request.Request(url, method='HEAD'), timeout=15) as r:
            return r.status == 200
    except Exception:
        return False


def pick_torch_index(accel: str, version: str) -> str | None:
    """PyTorch wheel index for this accelerator, or None for the default PyPI build."""
    def ver_tuple(v):
        return tuple(int(x) for x in re.findall(r'\d+', v)[:2]) or (0, 0)

    if accel == 'mps':
        return None
    if accel == 'cpu':
        return TORCH_INDEX + 'cpu' if sys.platform != 'darwin' else None
    have = ver_tuple(version)
    if accel == 'cuda':
        cands = ['cu130', 'cu129', 'cu128', 'cu126', 'cu124', 'cu121', 'cu118']
        tag = lambda c: (int(c[2:-1]), int(c[-1]))
    else:  # rocm: newest index whose major matches and minor <= installed
        cands = [f'rocm{a}.{b}' for a in (7, 6) for b in range(9, -1, -1)]
        tag = lambda c: ver_tuple(c[4:])
    for c in cands:
        t = tag(c)
        if t <= have and (accel == 'cuda' or t[0] == have[0]) and url_exists(TORCH_INDEX + c + '/torch/'):
            return TORCH_INDEX + c
    return None


def cmd_setup(args):
    py = sys.executable
    if not ((3, 10) <= sys.version_info[:2] <= (3, 12)):
        for cand in ('python3.12', 'python3.11', 'python3.10'):
            if shutil.which(cand):
                py = shutil.which(cand)
                break
        else:
            die('Kokoro needs Python 3.10–3.12; install one of those and re-run setup with it.')
    accel, ver = (args.accel, args.accel_version or '') if args.accel != 'auto' else detect_accelerator_without_torch()
    if accel == 'rocm' and not ver:
        ver = '6.0'
    log(f'accelerator: {accel} {ver}'.rstrip())
    index = pick_torch_index(accel, ver)
    if accel in ('cuda', 'rocm') and index is None:
        log(f'no PyTorch wheels found for {accel} {ver}; falling back to the CPU build')
        index = pick_torch_index('cpu', '')
    if not venv_python().exists():
        log(f'creating {VENV.relative_to(ROOT)} with {py}')
        subprocess.check_call([py, '-m', 'venv', str(VENV)])
    vpy = str(venv_python())
    pip = [vpy, '-m', 'pip', 'install', '--disable-pip-version-check']
    subprocess.check_call(pip + ['-q', '--upgrade', 'pip'])
    log(f'installing torch from {index or "PyPI"} (this can be a few GB for GPU builds)')
    subprocess.check_call(pip + ['torch'] + (['--index-url', index] if index else []))
    log('installing Kokoro and friends')
    subprocess.check_call(pip + ['-r', str(HERE / 'requirements.txt')])
    # misaki's Japanese G2P reads the full UniDic dictionary (≈500 MB, downloaded once).
    if subprocess.call([vpy, '-c', 'import unidic, os, sys; sys.exit(0 if os.path.exists(unidic.DICDIR) else 1)'],
                       stderr=subprocess.DEVNULL) != 0:
        subprocess.call([vpy, '-m', 'unidic', 'download'])
    # misaki's English G2P pip-installs this spaCy model on first use; do it now, not racily inside N workers.
    if subprocess.call([vpy, '-c', 'import en_core_web_sm'], stderr=subprocess.DEVNULL) != 0:
        subprocess.check_call([vpy, '-m', 'spacy', 'download', 'en_core_web_sm'], timeout=900)
    subprocess.check_call([vpy, str(Path(__file__).resolve()), 'fetch'])
    if not shutil.which('node'):
        log('warning: Node.js was not found; it is needed to read lines from js/cast/')
    log('done. Next:  python3 tools/voice/generate.py doctor')


def ensure_assets(model_id: str, voices=(), all_voices=False):
    """Download model weights and voice packs once, in this process, before any worker starts."""
    from huggingface_hub import hf_hub_download, list_repo_files
    files = ['config.json', 'kokoro-v1_0.pth']
    if all_voices:
        files += [f for f in list_repo_files(model_id) if f.startswith('voices/') and f.endswith('.pt')]
    else:
        files += [f'voices/{v}.pt' for v in sorted(set(voices))]
    for f in files:
        try:
            hf_hub_download(model_id, f, local_files_only=True)
        except Exception:
            log(f'downloading {model_id}/{f}')
            hf_hub_download(model_id, f)


def cmd_fetch(args):
    ensure_assets(load_config().get('model', 'hexgrad/Kokoro-82M'), all_voices=True)
    log('model and voices are cached')


# ------------------------------------------------------------------------------------ lines & config

def fnv1a(text: str) -> str:
    h = 0x811c9dc5
    for b in text.encode('utf-8'):
        h = ((h ^ b) * 0x01000193) & 0xffffffff
    return f'{h:08x}'


def load_lines() -> dict:
    node = shutil.which('node')
    if not node:
        die('Node.js is required to read lines from js/cast/')
    out = subprocess.run([node, str(EXTRACT_JS)], capture_output=True, text=True, cwd=ROOT)
    if out.returncode != 0:
        die(f'extract-lines.js failed:\n{out.stderr}')
    return json.loads(out.stdout)


def load_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except FileNotFoundError:
        return default


def save_json(path: Path, data, compact=False):
    tmp = path.with_suffix(path.suffix + '.tmp')
    text = json.dumps(data, ensure_ascii=False, sort_keys=True,
                      **({'separators': (',', ':')} if compact else {'indent': 1}))
    tmp.write_text(text + '\n', encoding='utf-8')
    os.replace(tmp, path)


def load_config() -> dict:
    cfg = load_json(CONFIG_PATH, None)
    if cfg is None:
        die(f'missing {CONFIG_PATH.relative_to(ROOT)}')
    return cfg


def parse_voice(spec) -> list[tuple[str, float]]:
    """'af_heart' | 'af_bella:0.7,af_sky:0.3' | [['af_bella', 0.7], ...] -> normalized [(name, weight)]."""
    if isinstance(spec, str):
        parts = []
        for p in spec.split(','):
            name, _, w = p.strip().partition(':')
            parts.append((name.strip(), float(w) if w else 1.0))
    else:
        parts = [(str(n), float(w)) for n, w in spec]
    total = sum(w for _, w in parts) or 1.0
    return [(n, w / total) for n, w in parts]


def kokoro_lang_code(lang: str, voices: list[tuple[str, float]], cfg_entry: dict) -> str:
    if cfg_entry.get('lang_code'):
        return cfg_entry['lang_code']
    if lang == 'ja':
        return 'j'
    return 'b' if voices[0][0].startswith('b') else 'a'


def output_settings(cfg: dict) -> dict:
    """{'format', 'ext', 'kbps'} from voices.json "output" (or the older "mp3": {"bitrate"} form)."""
    out = cfg.get('output') or {}
    fmt = (out.get('format') or 'mp3').lower()
    if fmt not in FORMATS:
        die(f'unknown output format {fmt!r} (use one of: {", ".join(FORMATS)})')
    kbps = out.get(f'{fmt}_kbps') or (cfg.get('mp3', {}).get('bitrate') if fmt == 'mp3' else None) \
        or FORMATS[fmt]['kbps']
    return {'format': fmt, 'ext': FORMATS[fmt]['ext'], 'kbps': int(kbps)}


def voice_settings(cfg: dict, char: str, lang: str) -> dict | None:
    entry = (cfg.get('characters', {}).get(char) or {}).get(lang)
    if not entry:
        return None
    post = {**cfg.get('post', {}), **entry.get('post', {})}
    voices = parse_voice(entry['voice'])
    s = {
        'model': cfg.get('model', 'hexgrad/Kokoro-82M'),
        'voice': voices,
        'speed': float(entry.get('speed', 1.0)),
        'lang_code': kokoro_lang_code(lang, voices, entry),
        'post': post,
        'output': output_settings(cfg),
    }
    s['fp'] = fnv1a(json.dumps(s, sort_keys=True))
    return s


# ------------------------------------------------------------------------------------------- status

def clip_path(char, lang, cid, ext='.mp3') -> Path:
    return AUDIO_DIR / char / lang / f'{cid}{ext}'


def clip_files(char, lang) -> dict[str, set[str]]:
    """{'.mp3': {ids}, '.opus': {ids}} for one companion/language folder."""
    d = AUDIO_DIR / char / lang
    found = {f['ext']: set() for f in FORMATS.values()}
    if d.is_dir():
        for p in d.iterdir():
            if p.suffix in found:
                found[p.suffix].add(p.stem)
    return found


def compute_state(lines, cfg, lock, chars=None, langs=LANGS):
    """Per (char, lang): which clips are ok / missing / stale / adopted / orphaned in the active format.

    `orphan` = files (any format) whose line is gone; `superseded` = other-format copies of lines that already
    have a clip in the active format (left over from switching formats). Lock entries are keyed by file name.
    """
    ext = output_settings(cfg)['ext']
    rows = []
    for char, data in lines.items():
        if chars and char not in chars:
            continue
        for lang in langs:
            s = voice_settings(cfg, char, lang)
            want = {e['id']: e for e in data[lang]}
            files = clip_files(char, lang)
            have = files[ext]
            orphan = sorted((e2, i) for e2, ids in files.items() for i in ids - set(want))
            superseded = sorted((e2, i) for e2, ids in files.items() if e2 != ext for i in ids & have & set(want))
            locked = ((lock.get(char) or {}).get(lang) or {}).get('clips', {})
            row = {'char': char, 'lang': lang, 'settings': s, 'want': want, 'have': have, 'ext': ext,
                   'ok': [], 'missing': [], 'stale': [], 'adopted': [], 'orphan': orphan, 'superseded': superseded}
            for cid in want:
                key = cid + ext
                if cid not in have:
                    row['missing'].append(cid)
                elif s is None:
                    row['ok'].append(cid)
                elif locked.get(key, ADOPTED) == ADOPTED:
                    row['adopted'].append(cid)
                elif locked[key] != s['fp']:
                    row['stale'].append(cid)
                else:
                    row['ok'].append(cid)
            rows.append(row)
    return rows


def cmd_status(args):
    lines, cfg, lock = load_lines(), load_config(), load_json(LOCK_PATH, {})
    rows = compute_state(lines, cfg, lock, args.char, args.lang or LANGS)
    o = output_settings(cfg)
    log(f'format: {o["format"]} @ {o["kbps"]} kbps\n')
    log(f'{"char":<8} {"lang":<4} {"lines":>5} {"ok":>5} {"missing":>7} {"stale":>5} {"adopted":>7} {"orphan":>6}  voice')
    tot = dict.fromkeys(('want', 'ok', 'missing', 'stale', 'adopted', 'orphan'), 0)
    for r in rows:
        s = r['settings']
        v = '(not configured)' if s is None else \
            '+'.join(f'{n}' if w == 1 else f'{n}:{w:.2f}' for n, w in s['voice']) + f' @{s["speed"]:g}'
        log(f'{r["char"]:<8} {r["lang"]:<4} {len(r["want"]):>5} {len(r["ok"]):>5} {len(r["missing"]):>7} '
            f'{len(r["stale"]):>5} {len(r["adopted"]):>7} {len(r["orphan"]):>6}  {v}')
        for k in tot:
            tot[k] += len(r[k])
    log(f'{"total":<13} {tot["want"]:>5} {tot["ok"]:>5} {tot["missing"]:>7} {tot["stale"]:>5} '
        f'{tot["adopted"]:>7} {tot["orphan"]:>6}')
    sup = sum(len(r['superseded']) for r in rows)
    if sup:
        log(f'\n{sup} clip(s) also exist in another format; `generate --prune` removes those copies.')
    if tot['adopted']:
        log('\nadopted = clips that predate voices.lock.json; they are kept as-is unless you pass --force.')
    if args.verbose:
        for r in rows:
            for k in ('missing', 'stale', 'orphan'):
                for cid in r[k]:
                    if k == 'orphan':
                        cid = cid[1] + cid[0]
                    text = r['want'][cid]['text'] if cid in r['want'] else ''
                    log(f'  {k:<7} {r["char"]}/{r["lang"]}/{cid}  {text}')


