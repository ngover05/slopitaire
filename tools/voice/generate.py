def write_manifest(lines, lock, cfg):
    """js/cast/voice-clips.js lists clips that exist on disk *and* belong to a current line. `v` is a cache-buster
    that only changes when a char/lang's clip set or voice changes, so unchanged clips stay browser-cached."""
    old = {}
    if MANIFEST_PATH.exists():
        text = MANIFEST_PATH.read_text(encoding='utf-8')
        m = re.search(r'=\s*(\{.*\})\s*;?\s*$', text, re.S)
        if m:
            old = json.loads(m.group(1))
    active = output_settings(cfg)['ext']
    out = {}
    for char, data in lines.items():
        for lang in LANGS:
            want = {e['id'] for e in data[lang]}
            files = clip_files(char, lang)
            # Mid-way through a format switch, keep listing the old format until the new one covers as many lines.
            ext = max(files, key=lambda e: (len(want & files[e]), e == active))
            ids = sorted(want & files[ext])
            if not ids:
                continue
            clips = ((lock.get(char) or {}).get(lang) or {}).get('clips', {})
            sig = fnv1a(json.dumps([ext] + [[i, clips.get(i + ext, ADOPTED)] for i in ids]))
            entry = lock.setdefault(char, {}).setdefault(lang, {})
            prev = (old.get(char) or {}).get(lang) or {}
            if entry.get('sig') == sig and entry.get('v'):
                v = entry['v']
            elif not entry.get('sig') and prev.get('ids') == ids and prev.get('v'):
                v = prev['v']           # first run with a lock: keep the version the game already ships
            else:
                v = sig
            entry['sig'], entry['v'] = sig, v
            m = {'v': v, 'ids': ids}
            if ext != '.mp3':  # js/cast/voice.js assumes mp3 when "ext" is absent
                m = {'v': v, 'ext': ext[1:], 'ids': ids}
            out.setdefault(char, {})[lang] = m
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    new = f'{MANIFEST_HEADER}\nwindow.VOICE_CLIPS = {body};\n'
    if not MANIFEST_PATH.exists() or MANIFEST_PATH.read_text(encoding='utf-8') != new:
        MANIFEST_PATH.write_text(new, encoding='utf-8')
        log(f'updated {MANIFEST_PATH.relative_to(ROOT)}')
    return out


def cmd_manifest(args):
    lines, cfg, lock = load_lines(), load_config(), load_json(LOCK_PATH, {})
    if args.format:
        cfg.setdefault('output', {})['format'] = args.format
    write_manifest(lines, lock, cfg)
    save_json(LOCK_PATH, lock)


def cmd_adopt(args):
    """Mark existing clips as rendered with the current config (after confirming it with `match`)."""
    lines, cfg, lock = load_lines(), load_config(), load_json(LOCK_PATH, {})
    n = 0
    for r in compute_state(lines, cfg, lock, args.char, args.lang or LANGS):
        if r['settings'] is None:
            continue
        clips = lock.setdefault(r['char'], {}).setdefault(r['lang'], {}).setdefault('clips', {})
        for cid in r['adopted'] + (r['stale'] if args.stale else []):
            clips[cid + r['ext']] = r['settings']['fp']
            n += 1
    save_json(LOCK_PATH, lock)
    log(f'adopted {n} clips into {LOCK_PATH.relative_to(ROOT)}')


# ------------------------------------------------------------------------------------ hardware plan

def torch_devices(include_integrated=False):
    """Usable accelerators as dicts: {device, name, vram_gb, free_gb, backend}."""
    import torch
    devs = []
    if torch.cuda.is_available():
        backend = 'rocm' if getattr(torch.version, 'hip', None) else 'cuda'
        for i in range(torch.cuda.device_count()):
            p = torch.cuda.get_device_properties(i)
            integrated = bool(getattr(p, 'is_integrated', 0))
            if integrated and not include_integrated:
                continue  # APU graphics share system RAM and are slower than the CPU path for this model
            try:
                free, total = torch.cuda.mem_get_info(i)
            except Exception:
                free = total = p.total_memory
            devs.append({'device': f'cuda:{i}', 'name': p.name, 'backend': backend,
                         'arch': getattr(p, 'gcnArchName', '') or f'sm_{p.major}{p.minor}',
                         'vram_gb': round(total / 2**30, 1), 'free_gb': round(free / 2**30, 1),
                         'integrated': integrated})
    elif getattr(torch.backends, 'mps', None) and torch.backends.mps.is_available():
        devs.append({'device': 'mps', 'name': 'Apple GPU', 'backend': 'mps', 'arch': platform.machine(),
                     'vram_gb': None, 'free_gb': None})
    elif hasattr(torch, 'xpu') and torch.xpu.is_available():
        for i in range(torch.xpu.device_count()):
            p = torch.xpu.get_device_properties(i)
            devs.append({'device': f'xpu:{i}', 'name': p.name, 'backend': 'xpu', 'arch': '',
                         'vram_gb': round(p.total_memory / 2**30, 1), 'free_gb': None})
    return devs


def hw_fingerprint(devs):
    import torch
    key = [cpu_name(), physical_cores(), torch.__version__, [(d['device'], d['name'], d['vram_gb']) for d in devs]]
    return fnv1a(json.dumps(key))


def make_plan(args, devs=None):
    """Decide which devices to use and how many worker processes / threads each gets.

    Returns a list of groups: {device, workers, threads, label}. Every worker is a separate process with its
    own model copy, so text processing (CPU) for one line overlaps with synthesis (GPU) for another.
    """
    if devs is None:
        devs = torch_devices(include_integrated=bool(args.device and args.device != 'auto'))
    phys, logical, ram = physical_cores(), logical_cores(), available_ram_gb()
    ram_cap = max(1, int((ram - 1.0) / RAM_PER_WORKER_GB))
    profile = load_json(PROFILE_PATH, {})
    tuned = profile.get('workers_per_device') if profile.get('fingerprint') == hw_fingerprint(devs) else None

    want = (args.device or 'auto').lower()
    if want == 'cpu' or (want == 'auto' and not devs):
        # Few multi-threaded workers beat many single-threaded ones on CPU: G2P is serial, synthesis is not.
        workers = args.workers or (tuned or {}).get('cpu') or max(1, min(phys // 2 or 1, ram_cap))
        threads = args.threads or max(1, phys // workers)
        return [{'device': 'cpu', 'workers': workers, 'threads': threads, 'label': cpu_name()}]

    if want != 'auto':
        sel = [d for d in devs if d['device'] == want or (want in ('cuda', 'gpu') and d['device'].startswith('cuda'))
               or d['device'].split(':')[0] == want]
        if not sel:
            die(f'device {want!r} not available (found: {", ".join(d["device"] for d in devs) or "none"})')
        devs = sel

    groups = []
    cpu_budget = max(1, logical - 1)  # each GPU worker spends real CPU time on G2P and tensor prep
    for d in devs:
        if args.workers:
            n = args.workers
        elif tuned and d['device'] in tuned:
            n = tuned[d['device']]
        else:
            vram = d['free_gb'] if d['free_gb'] is not None else (d['vram_gb'] or 8)
            n = max(1, min(MAX_WORKERS_PER_GPU, int((vram - 0.5) / VRAM_PER_WORKER_GB), phys // max(1, len(devs))))
        groups.append({'device': d['device'], 'workers': n, 'label': f'{d["name"]} ({d["backend"]})'})
    total = sum(g['workers'] for g in groups)
    if not args.workers and total > ram_cap:  # trim the biggest groups first when RAM is the limit
        while total > ram_cap:
            g = max(groups, key=lambda g: g['workers'])
            if g['workers'] == 1:
                break
            g['workers'] -= 1
            total -= 1
    for g in groups:
        g['threads'] = args.threads or max(1, min(4, cpu_budget // max(1, total)))
    return groups


