# Everything below runs inside worker processes (spawned, so CUDA/ROCm state is never forked).

_W: dict = {}


def _set_runtime_env(device: str):
    os.environ.setdefault('TOKENIZERS_PARALLELISM', 'false')
    os.environ.setdefault('MIOPEN_FIND_MODE', 'FAST')        # ROCm: skip slow kernel autotuning at startup
    os.environ.setdefault('PYTORCH_ENABLE_MPS_FALLBACK', '1')  # MPS: run the odd unsupported op on CPU


def _worker_init(device: str, threads: int, model_id: str, lang_codes: list[str], warm=None):
    import warnings
    warnings.filterwarnings('ignore')
    _set_runtime_env(device)
    import torch
    torch.set_num_threads(threads)
    try:
        torch.set_num_interop_threads(1)
    except RuntimeError:
        pass
    if getattr(torch.version, 'hip', None) and os.environ.get('VOICEGEN_MIOPEN') != '1':
        # MIOpen JIT-compiles a dropout kernel for LSTMs that needs rocRAND headers the pip wheels don't ship
        # ("Code object build failed. Source: MIOpenDropoutHIP.cpp"). PyTorch's own HIP kernels are fast here.
        torch.backends.cudnn.enabled = False
    _W.update(device=device, model_id=model_id, pipes={}, voices={}, model=None)
    for lc in lang_codes:
        _pipe(lc)
    for lc, voices in warm or ():  # first call JIT-compiles kernels (notably on ROCm); keep it out of timings
        _synth(lc, voices, 1.0, 'テストです。' if lc == 'j' else 'Warming up.')


def _pipe(lang_code: str):
    p = _W['pipes'].get(lang_code)
    if p is None:
        from kokoro import KModel, KPipeline
        if _W['model'] is None:
            _W['model'] = KModel(repo_id=_W['model_id']).to(_W['device']).eval()
        p = KPipeline(lang_code=lang_code, repo_id=_W['model_id'], model=_W['model'])
        _W['pipes'][lang_code] = p
    return p


def _voice_pack(pipe, voices):
    key = tuple(voices)
    pack = _W['voices'].get(key)
    if pack is None:
        packs = [pipe.load_single_voice(n) * w for n, w in voices]
        pack = packs[0] if len(packs) == 1 else sum(packs[1:], packs[0])
        _W['voices'][key] = pack
    return pack


def _synth(lang_code, voices, speed, text):
    import torch
    try:
        return _synth_once(lang_code, voices, speed, text)
    except RuntimeError as e:
        msg = str(e).lower()
        if torch.backends.cudnn.enabled and ('miopen' in msg or 'cudnn' in msg):
            torch.backends.cudnn.enabled = False  # vendor RNN/conv library broken on this setup: use native kernels
            return _synth_once(lang_code, voices, speed, text)
        raise


def _synth_once(lang_code, voices, speed, text):
    import numpy as np
    import torch
    pipe = _pipe(lang_code)
    pack = _voice_pack(pipe, voices)
    chunks = []
    with torch.inference_mode():
        for r in pipe(text, voice=pack, speed=speed):
            if r.audio is not None:
                chunks.append(r.audio.detach().float().cpu().numpy())
    return np.concatenate(chunks) if chunks else np.zeros(0, dtype=np.float32)


def postprocess(audio, post: dict):
    import numpy as np
    a = np.asarray(audio, dtype=np.float32)
    if post.get('trim_db') is not None and a.size:
        thr = 10 ** (post['trim_db'] / 20) * (np.abs(a).max() or 1)
        idx = np.flatnonzero(np.abs(a) > thr)
        if idx.size:
            pad = int(SAMPLE_RATE * post.get('pad_ms', 60) / 1000)
            a = a[max(0, idx[0] - pad): idx[-1] + pad]
    if post.get('peak_db') is not None and a.size:
        peak = np.abs(a).max()
        if peak > 0:
            a = a * (10 ** (post['peak_db'] / 20) / peak)
    gain = post.get('gain_db')
    if gain:
        a = a * 10 ** (gain / 20)
    return np.clip(a, -1.0, 1.0)


def encode_mp3(audio, bitrate: int) -> bytes:
    import lameenc
    import numpy as np
    enc = lameenc.Encoder()
    enc.set_bit_rate(int(bitrate))
    enc.set_in_sample_rate(SAMPLE_RATE)
    enc.set_channels(1)
    enc.set_quality(2)  # 2 = high quality, still far faster than synthesis
    pcm = (np.asarray(audio) * 32767).astype('<i2').tobytes()
    return bytes(enc.encode(pcm) + enc.flush())


def encode_opus(audio, kbps: int, path: Path):
    """Ogg Opus via the libopus bundled in the soundfile wheel (no ffmpeg needed). libsndfile exposes bitrate
    only as a 0..1 "compression level" that maps linearly onto 256..6 kbps per channel, so invert that."""
    import soundfile as sf
    level = min(1.0, max(0.0, (256 - kbps) / 250))
    sf.write(str(path), audio, SAMPLE_RATE, format='OGG', subtype='OPUS', compression_level=level)


def _render_job(job: dict):
    """Synthesize one line and write its clip atomically. Returns (job key, audio seconds, error or None)."""
    t0 = time.perf_counter()
    try:
        try:
            audio = _synth(job['lang_code'], job['voice'], job['speed'], job['text'])
        except RuntimeError as e:  # transient GPU OOM when several workers peak together: free and retry once
            if 'out of memory' not in str(e).lower():
                raise
            import torch
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            time.sleep(0.5)
            audio = _synth(job['lang_code'], job['voice'], job['speed'], job['text'])
        if audio.size == 0:
            raise RuntimeError('model produced no audio')
        audio = postprocess(audio, job['post'])
        out = Path(job['out'])
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(f'.{os.getpid()}.tmp')
        if out.suffix == '.wav':
            import soundfile as sf
            sf.write(str(tmp), audio, SAMPLE_RATE, format='WAV')
        elif out.suffix == '.opus':
            encode_opus(audio, job.get('kbps') or FORMATS['opus']['kbps'], tmp)
        else:
            tmp.write_bytes(encode_mp3(audio, job.get('kbps') or FORMATS['mp3']['kbps']))
        os.replace(tmp, out)
        return job['key'], len(audio) / SAMPLE_RATE, time.perf_counter() - t0, None
    except Exception as e:
        return job['key'], 0.0, time.perf_counter() - t0, f'{e.__class__.__name__}: {e}'


# ----------------------------------------------------------------------------------------- dispatch

def run_jobs(jobs: list[dict], groups: list[dict], model_id: str, on_done=None, quiet=False, warm=False,
             stamps=None):
    """Run jobs across all device groups with work-stealing: every group pulls the next job as soon as it has a
    free worker, so a fast GPU and a slow one (or GPU + CPU) each get as much work as they can handle."""
    import concurrent.futures as cf
    import multiprocessing as mp

    if not jobs:
        return [], 0.0
    ctx = mp.get_context('spawn')
    lang_codes = sorted({j['lang_code'] for j in jobs})
    ensure_assets(model_id, [n for j in jobs for n, _ in j['voice']])
    warm_list = list({j['lang_code']: (j['lang_code'], j['voice']) for j in jobs}.values()) if warm else None
    pools = []

    def start(g, restarts=0):
        n = min(g['workers'], len(jobs))
        ex = cf.ProcessPoolExecutor(max_workers=n, mp_context=ctx, initializer=_worker_init,
                                    initargs=(g['device'], g['threads'], model_id, lang_codes, warm_list))
        pools.append({'ex': ex, 'cap': n * 2, 'inflight': 0, 'group': g, 'restarts': restarts})

    for g in groups:
        if g['workers'] >= 1:
            start(g)
    queue = sorted(jobs, key=lambda j: -len(j['text']))  # longest first keeps the tail short
    pending, failures = {}, []
    done = 0
    audio_s = 0.0
    t0 = time.perf_counter()
    tty = sys.stderr.isatty() and not quiet
    last_print = 0.0

    def broken(p, why):
        """A worker process died, which poisons its whole pool. Restart it twice, then give up on that device;
        if every device is gone, finish on the CPU rather than failing the run."""
        if p not in pools:
            return
        pools.remove(p)
        p['ex'].shutdown(wait=False, cancel_futures=True)
        g = p['group']
        if p['restarts'] < 2:
            log(f'\n{g["device"]} worker died ({why}); restarting its workers')
            start(g, p['restarts'] + 1)
        elif not pools and g['device'] != 'cpu':
            log(f'\n{g["device"]} keeps failing ({why}); continuing on the CPU')
            w = max(1, min(physical_cores() // 2, int((available_ram_gb() - 1.0) / RAM_PER_WORKER_GB)))
            start({'device': 'cpu', 'workers': w, 'threads': max(1, physical_cores() // w), 'label': 'cpu fallback'})
        else:
            log(f'\ngiving up on {g["device"]} ({why})')

    def fill():
        import concurrent.futures.process as cfp
        while queue and pools:
            free = [p for p in pools if p['inflight'] < p['cap']]
            if not free:
                return
            p = min(free, key=lambda p: p['inflight'] / p['cap'])
            job = queue.pop(0)
            try:
                fut = p['ex'].submit(_render_job, job)
            except (cfp.BrokenProcessPool, RuntimeError) as e:
                queue.insert(0, job)
                broken(p, e)
                continue
            pending[fut] = (p, job)
            p['inflight'] += 1

    try:
        fill()
        while pending:
            finished, _ = cf.wait(list(pending), return_when=cf.FIRST_COMPLETED)
            for fut in finished:
                p, job = pending.pop(fut)
                p['inflight'] -= 1
                try:
                    key, secs, _, err = fut.result()
                except Exception as e:  # worker crashed (driver reset, killed by the OOM killer, ...)
                    job['tries'] = job.get('tries', 0) + 1
                    broken(p, f'{e.__class__.__name__}: {e}' if str(e) else e.__class__.__name__)
                    # Usually the device's fault, not the line's: retry it. Restarts are capped per device, so a line
                    # that crashes every worker still ends (2 restarts x devices + CPU fallback = at most 7 tries).
                    if job['tries'] < 7 and pools:
                        queue.insert(0, job)
                        continue
                    key, secs, err = job['key'], 0.0, f'worker died: {e.__class__.__name__}'
                done += 1
                if err:
                    failures.append((job, err))
                    log(f'\nfailed {key}: {err}')
                else:
                    audio_s += secs
                    if stamps is not None:
                        stamps.append(time.perf_counter())
                    if on_done:
                        on_done(job)
            fill()
            if not pools and queue:
                for job in queue:
                    failures.append((job, 'no working device left'))
                done += len(queue)
                queue.clear()
            now = time.perf_counter()
            if not quiet and (now - last_print > 0.5 or not pending):
                last_print = now
                el = now - t0
                rate = done / el if el else 0
                eta = (len(jobs) - done) / rate if rate else 0
                msg = (f'{done}/{len(jobs)} clips  {rate:.1f} clips/s  {audio_s / el if el else 0:.1f}x realtime  '
                       f'eta {int(eta // 60)}:{int(eta % 60):02d}')
                log(('\r' + msg + '   ') if tty else msg, end='' if tty else '\n')
        if tty:
            log()
    finally:
        for p in pools:
            p['ex'].shutdown(wait=True, cancel_futures=True)
    return failures, time.perf_counter() - t0


def build_jobs(rows, include, out_root=AUDIO_DIR):
    jobs = []
    for r in rows:
        s = r['settings']
        if s is None:
            if r['missing']:
                log(f'skip {r["char"]}/{r["lang"]}: no voice configured in voices.json ({len(r["missing"])} lines)')
            continue
        for kind in include:
            for cid in r[kind]:
                jobs.append({
                    'key': f'{r["char"]}/{r["lang"]}/{cid}', 'char': r['char'], 'lang': r['lang'], 'id': cid,
                    'text': r['want'][cid]['text'], 'voice': s['voice'], 'speed': s['speed'],
                    'lang_code': s['lang_code'], 'post': s['post'], 'kbps': s['output']['kbps'], 'fp': s['fp'],
                    'file': cid + s['output']['ext'],
                    'out': str(Path(out_root) / r['char'] / r['lang'] / (cid + s['output']['ext'])),
                })
    return jobs


def cmd_generate(args):
    lines, cfg, lock = load_lines(), load_config(), load_json(LOCK_PATH, {})
    if args.format:
        cfg.setdefault('output', {})['format'] = args.format
        if args.kbps:
            cfg['output'][f'{args.format}_kbps'] = args.kbps
    elif args.kbps:
        cfg.setdefault('output', {})[f'{output_settings(cfg)["format"]}_kbps'] = args.kbps
    o = output_settings(cfg)
    rows = compute_state(lines, cfg, lock, args.char, args.lang or LANGS)
    include = ['missing', 'stale'] + (['adopted', 'ok'] if args.force else [])
    jobs = build_jobs(rows, include)
    if args.limit:
        jobs = jobs[:args.limit]
    orphans = [(r['char'], r['lang'], i, e) for r in rows for e, i in r['orphan'] + r['superseded']]
    log(f'{len(jobs)} clip(s) to render as {o["format"]} @ {o["kbps"]} kbps' +
        (f', {len(orphans)} orphaned / other-format clip(s) on disk' + ('' if args.prune else ' (--prune removes)')
         if orphans else ''))
    if args.dry_run:
        for j in jobs:
            log(f'  {j["key"]}  {j["text"]}')
        for c, l, i, e in orphans:
            log(f'  prune {c}/{l}/{i}{e}')
        return
    groups = make_plan(args)
    if jobs:
        for g in groups:
            log(f'using {g["device"]}: {g["workers"]} worker(s) x {g["threads"]} thread(s) — {g["label"]}')

    since_save = [0]

    def on_done(job):
        lock.setdefault(job['char'], {}).setdefault(job['lang'], {}).setdefault('clips', {})[job['file']] = job['fp']
        since_save[0] += 1
        if since_save[0] >= 25:  # interrupted runs resume where they stopped
            save_json(LOCK_PATH, lock)
            since_save[0] = 0

    failures = []
    try:
        failures, el = run_jobs(jobs, groups, cfg.get('model', 'hexgrad/Kokoro-82M'), on_done)
        if jobs:
            log(f'rendered {len(jobs) - len(failures)} clip(s) in {el:.1f}s')
    except KeyboardInterrupt:
        log('\ninterrupted — progress saved; run again to continue')
    finally:
        if args.prune and orphans:
            # superseded copies were computed before rendering, so each still has an active-format clip
            for c, l, i, e in orphans:
                clip_path(c, l, i, e).unlink(missing_ok=True)
            log(f'pruned {len(orphans)} clip(s)')
        for c in list(lock):  # drop lock entries for clips that no longer exist
            for l in list(lock[c]):
                clips = lock[c][l].get('clips', {})
                for name in [k for k in clips if not (AUDIO_DIR / c / l / k).exists()]:
                    del clips[name]
        write_manifest(lines, lock, cfg)
        save_json(LOCK_PATH, lock)
    if failures:
        die(f'{len(failures)} clip(s) failed; re-run to retry them')


