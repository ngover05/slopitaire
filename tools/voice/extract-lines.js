#!/usr/bin/env node
/* Prints every spoken voice line in js/cast/ as JSON, for tools/voice/generate.py.
 *
 * It runs the game's own cast scripts (js/cast/*.js and js/cast/characters/*.js, in the order index.html loads
 * them) in a sandbox and uses their Voice.speakable() and Voice.clipId(), so the text that gets rendered and the
 * clip file names are exactly what the game computes at runtime.
 *
 * Output: { "<char>": { "en": [{ "id", "text", "events": [...] }], "ja": [...] }, ... }
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..', '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
// the clip manifest is generated by generate.py; lines are read without it
const castScripts = [...html.matchAll(/<script\b[^>]*\bsrc="(js\/cast\/[^"]+\.js)"/g)]
  .map((m) => m[1])
  .filter((src) => src !== 'js/cast/voice-clips.js');
if (!castScripts.length) throw new Error('no js/cast/ scripts found in index.html');

const sandbox = {
  window: {},
  TextEncoder,
  setTimeout: () => 0,
  clearTimeout: () => {},
  console,
};
vm.createContext(sandbox);
for (const rel of castScripts) {
  const file = path.join(root, rel);
  vm.runInContext(fs.readFileSync(file, 'utf8'), sandbox, { filename: file });
}
// `const` declarations at script top level don't become context properties, so hand them back explicitly.
vm.runInContext('globalThis.__out = { Voice, Cast };', sandbox);
const { Voice, Cast } = sandbox.__out;

const out = {};
for (const key of Cast.keys) {
  const c = Cast.CAST[key];
  if (!c.voice || !c.lines) continue; // non-speaking companions (e.g. the cat) have no clips
  const langs = { en: new Map(), ja: new Map() };
  for (const [ev, pool] of Object.entries(c.lines)) {
    for (const item of pool) {
      if (!Array.isArray(item)) continue;
      for (const [lang, raw] of [['ja', item[1]], ['en', item[2]]]) {
        const text = Voice.speakable(raw || '', lang === 'ja');
        if (!text) continue;
        const id = Voice.clipId(text);
        const m = langs[lang];
        if (!m.has(id)) m.set(id, { id, text, events: [] });
        const e = m.get(id);
        if (!e.events.includes(ev)) e.events.push(ev);
      }
    }
  }
  out[key] = { name: c.name, en: [...langs.en.values()], ja: [...langs.ja.values()] };
}
process.stdout.write(JSON.stringify(out));
