'use strict';
/* Slopitaire sound effects renderer: pre-renders every variant of every sound effect into audio/sfx/ (one Opus file
 * per effect) and writes js/audio/sfx-files.js. Runs the game's own SFX code in Chromium's Web Audio engine
 * (Electron), so the files sound like the live synth. See README.md.
 *
 *   npm run sfx                       render what is missing or out of date
 *   npm run sfx -- status             show what is up to date
 *   npm run sfx -- --force place win  re-render some effects (space or comma separated)
 */
const { app, BrowserWindow, ipcMain } = require('electron');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn, spawnSync } = require('node:child_process');

const TOOL_VERSION = 1;
const ROOT = path.resolve(__dirname, '..', '..');
const OUT_DIR = 'audio/sfx'; // relative to ROOT, and the URL the game fetches from
const MANIFEST = path.join(ROOT, 'js', 'audio', 'sfx-files.js');
const CONFIG = path.join(__dirname, 'sfx.json');
const RENDER_JS = path.join(__dirname, 'render.js');
// What an effect sounds like is captured by its fingerprint (every Web Audio call it makes, see render.js), so only
// effects whose sound changed are re-rendered. These settings and the render code apply to all of them.
const SETTINGS = ['format', 'kbps', 'sampleRate', 'seconds', 'floorDb', 'gapSeconds', 'seed'];
// decode check: a clip's level may differ this much from what went in, and the file's SNR must be at least this
const MAX_LEVEL_DB = 1;
const MIN_SNR_DB = 8;

// ---------- command line ----------

function usage() {
  return `usage: npm run sfx -- [render|status] [effect ...] [options]

  render (default)   render missing or out-of-date effects
  status             list each effect's state without rendering

  effect ...         limit to these effects (space or comma separated)
  --force            render even if up to date
  --kbps N           Opus bitrate (default ${readConfig().kbps})
  --jobs N           parallel render windows (default: half the CPU cores, at most 8)
  --prune            delete files in ${OUT_DIR} that belong to no effect
`;
}

function parseArgs(argv) {
  const o = { cmd: 'render', effects: [], force: false, prune: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const val = () => {
      const v = argv[++i];
      if (v == null) throw new Error(`${a} needs a value`);
      return v;
    };
    if (a === 'render' || a === 'status') o.cmd = a;
    else if (a === '--help' || a === '-h') o.cmd = 'help';
    else if (a === '--force') o.force = true;
    else if (a === '--prune') o.prune = true;
    else if (a === '--kbps') o.kbps = Number(val());
    else if (a === '--jobs') o.jobs = Number(val());
    else if (a.startsWith('--')) throw new Error(`unknown option ${a}`);
    else o.effects.push(...a.split(',').filter(Boolean));
  }
  return o;
}

// electron [chromium switches] tools/sfx/main.js [args]: keep only what follows this script
function scriptArgs() {
  const i = process.argv.findIndex((a) => path.resolve(a) === __filename || path.resolve(a) === __dirname);
  return process.argv.slice(i >= 0 ? i + 1 : 2);
}

// ---------- files ----------

function readConfig() {
  return JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
}

function readManifest() {
  try {
    const src = fs.readFileSync(MANIFEST, 'utf8');
    return JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
  } catch {
    return { dir: OUT_DIR, format: 'opus', sampleRate: 48000, effects: {} };
  }
}

// effects in `order` (the game decodes them in this order, so the common ones come first)
function writeManifest(m, order) {
  const effects = {};
  for (const name of order) if (m.effects[name]) effects[name] = m.effects[name];
  const body = JSON.stringify({ ...m, effects }, (k, v) => (k === 'vars' ? `@@${JSON.stringify(v)}@@` : v), 2)
    .replace(/"@@(.*?)@@"/g, (_, s) => JSON.parse(`"${s}"`)); // keep each effect's slice table on one line
  const text = `/* Generated by tools/sfx (npm run sfx). Do not edit by hand.
 * Pre-rendered sound effects: one Opus file per effect holding every variant of it back to back.
 * vars: variant key (SfxSuite.VARIANTS[name].key(...args).join(' '), '' for effects without one) -> its takes, each
 * [start, length] in samples at sampleRate · v: content hash, appended as ?v= so caches pick up re-rendered files ·
 * src: hash of the effect's fingerprint and the render settings. */
window.SFX_FILES = ${body};
`;
  writeAtomic(MANIFEST, text);
}

function writeAtomic(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, data);
  fs.renameSync(tmp, file);
}

const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');
const fileHash = (file) => sha(fs.readFileSync(file)).slice(0, 10);

function toolHash(cfg) {
  const settings = Object.fromEntries(SETTINGS.map((k) => [k, cfg[k]]));
  return sha(`v${TOOL_VERSION}\n${JSON.stringify(settings)}\n${fs.readFileSync(RENDER_JS, 'utf8')}`);
}

function effectSrc(tool, e) {
  const h = crypto.createHash('sha256').update(`${tool}\n${e.name}\n${e.takes}\n`);
  for (const v of e.variants) h.update(`${v.keys.join('|')}\n${v.fp}\n\n`);
  return h.digest('hex').slice(0, 12);
}

function effectState(e, entry) {
  if (!entry) return 'missing';
  const file = path.join(ROOT, OUT_DIR, entry.file);
  if (!fs.existsSync(file)) return 'missing';
  if (fileHash(file) !== entry.v) return 'changed on disk';
  return entry.src === e.src ? 'up to date' : 'out of date';
}

// ---------- encoder ----------

function findFfmpeg() {
  const bin = process.env.FFMPEG || 'ffmpeg';
  const r = spawnSync(bin, ['-hide_banner', '-encoders'], { encoding: 'utf8' });
  if (r.error || r.status !== 0) throw new Error(`ffmpeg not found (${bin}). Install it, or set FFMPEG=/path/to/ffmpeg.`);
  if (!/libopus/.test(r.stdout)) throw new Error(`${bin} was built without libopus.`);
  return bin;
}

function encodeOpus(ffmpeg, pcm, sampleRate, kbps, outFile) {
  return new Promise((resolve, reject) => {
    const tmp = `${outFile}.${process.pid}.tmp`;
    const p = spawn(ffmpeg, [
      '-hide_banner', '-loglevel', 'error', '-y',
      '-f', 'f32le', '-ar', String(sampleRate), '-ac', '1', '-i', 'pipe:0',
      '-c:a', 'libopus', '-b:a', `${kbps}k`, '-vbr', 'on', '-compression_level', '10', '-application', 'audio',
      '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', '-f', 'ogg', tmp,
    ], { stdio: ['pipe', 'ignore', 'pipe'] });
    let err = '';
    p.stderr.on('data', (d) => { err += d; });
    p.on('error', reject);
    p.on('close', (code) => {
      if (code !== 0) {
        fs.rmSync(tmp, { force: true });
        reject(new Error(`ffmpeg exited ${code}: ${err.trim()}`));
        return;
      }
      fs.renameSync(tmp, outFile);
      resolve();
    });
    p.stdin.on('error', () => {}); // reported through 'close'
    p.stdin.end(Buffer.from(pcm.buffer, pcm.byteOffset, pcm.byteLength));
  });
}

// ---------- render windows ----------

class Worker {
  constructor() {
    this.win = new BrowserWindow({
      show: false,
      webPreferences: { preload: path.join(__dirname, 'preload.js'), backgroundThrottling: false },
    });
    this.pending = new Map();
    this.ready = new Promise((res) => { this.onReady = res; });
    this.win.loadFile(path.join(__dirname, 'render.html'));
  }

  run(kind, payload) {
    const id = Worker.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.win.webContents.send('job', id, kind, payload);
    });
  }
}
Worker.nextId = 1;

function wireWorkers(workers) {
  const byContents = (e) => workers.find((w) => w.win.webContents === e.sender);
  ipcMain.on('ready', (e) => { const w = byContents(e); if (w) w.onReady(); });
  ipcMain.on('done', (e, id, result) => {
    const w = byContents(e), p = w && w.pending.get(id);
    if (p) { w.pending.delete(id); p.resolve(result); }
  });
  ipcMain.on('fail', (e, id, message) => {
    const w = byContents(e), p = w && w.pending.get(id);
    if (p) { w.pending.delete(id); p.reject(new Error(message)); }
  });
}

// run tasks on whichever window is free
async function pool(workers, tasks) {
  const queue = tasks.slice();
  await Promise.all(workers.map(async (w) => {
    await w.ready;
    while (queue.length) await queue.shift()(w);
  }));
}

// ---------- packing ----------

// All clips of an effect back to back, `gap` samples of silence apart (more than an Opus frame, so the codec doesn't
// smear one clip into the next). Returns the samples and each clip's place in them.
function pack(clips, gap) {
  let total = 0;
  const places = clips.map((c, i) => {
    const start = total + (i ? gap : 0);
    total = start + c.pcm.length;
    return { start, len: c.pcm.length };
  });
  const pcm = new Float32Array(total);
  clips.forEach((c, i) => pcm.set(c.pcm, places[i].start));
  for (const p of places) {
    let e = 0;
    for (let i = p.start; i < p.start + p.len; i++) e += pcm[i] * pcm[i];
    p.energy = e;
  }
  return { pcm, places };
}

// ---------- main ----------

const fmtS = (s) => `${s.toFixed(2)}s`;
const fmtKB = (n) => `${(n / 1024).toFixed(1)} KB`;

async function main() {
  const opts = parseArgs(scriptArgs());
  if (opts.cmd === 'help') { process.stdout.write(usage()); return 0; }

  const cfg = readConfig();
  if (opts.kbps) cfg.kbps = opts.kbps;
  if (!(cfg.kbps >= 6 && cfg.kbps <= 256)) throw new Error('--kbps must be between 6 and 256');
  if (cfg.format !== 'opus') throw new Error(`unsupported format ${cfg.format} (only opus)`);

  const jobs = Math.max(1, Math.min(opts.jobs || Math.min(8, Math.max(1, os.cpus().length >> 1)), 32));
  const workers = [new Worker()];
  wireWorkers(workers);
  await workers[0].ready;
  const list = await workers[0].run('list', { sampleRate: cfg.sampleRate, seed: cfg.seed });
  const byName = new Map(list.map((e) => [e.name, e]));
  const order = list.map((e) => e.name);

  const problems = list.flatMap((e) => e.problems);
  if (problems.length) {
    for (const p of problems) console.error(`key check: ${p}`);
    throw new Error('SfxSuite.VARIANTS key() does not match what the effect does (js/audio/sfx.js); fix it before rendering');
  }
  for (const n of opts.effects) {
    if (!byName.has(n)) throw new Error(`unknown effect "${n}" (effects: ${order.join(', ')})`);
  }
  const selected = opts.effects.length ? opts.effects.map((n) => byName.get(n)) : list;

  const tool = toolHash(cfg);
  for (const e of list) e.src = effectSrc(tool, e);
  const manifest = readManifest();
  manifest.dir = OUT_DIR;
  manifest.format = cfg.format;
  manifest.sampleRate = cfg.sampleRate;
  manifest.effects = manifest.effects || {};

  const todo = [];
  for (const e of selected) {
    const entry = manifest.effects[e.name];
    const state = effectState(e, entry);
    const size = state !== 'missing' ? fs.statSync(path.join(ROOT, OUT_DIR, entry.file)).size : 0;
    console.log(`${e.name.padEnd(15)} ${state.padEnd(16)} ${String(e.variants.length).padStart(3)} variant(s)`
      + `${e.takes > 1 ? ` x ${e.takes} takes` : ''}${size ? ` · ${fmtKB(size)}` : ''}`);
    if (opts.force || state !== 'up to date') todo.push(e);
  }

  const known = new Set(order.map((n) => `${n}.opus`));
  const outDir = path.join(ROOT, OUT_DIR);
  const stray = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((f) => !known.has(f)) : [];
  for (const f of stray) {
    if (opts.prune && opts.cmd === 'render') {
      fs.rmSync(path.join(outDir, f), { recursive: true, force: true });
      console.log(`pruned ${OUT_DIR}/${f}`);
    } else console.log(`${OUT_DIR}/${f} belongs to no effect (--prune deletes it)`);
  }
  const dropped = Object.keys(manifest.effects).filter((n) => !byName.has(n));
  for (const n of dropped) delete manifest.effects[n];

  if (opts.cmd === 'status' || !todo.length) {
    if (opts.cmd === 'render') {
      if (dropped.length) writeManifest(manifest, order);
      console.log('nothing to render');
    }
    return 0;
  }

  const ffmpeg = findFfmpeg();
  for (let i = 1; i < Math.min(jobs, todo.length); i++) workers.push(new Worker());
  console.log(`\nrendering ${todo.length} effect(s) on ${workers.length} window(s), Opus ${cfg.kbps} kbps`);
  fs.mkdirSync(outDir, { recursive: true });

  const t0 = Date.now();
  const gap = Math.round(cfg.gapSeconds * cfg.sampleRate);
  let failed = 0, loud = 0;
  await pool(workers, todo.map((e) => async (w) => {
    const r = await w.run('render', {
      name: e.name, part: e.part, takes: e.takes,
      variants: e.variants.map((v) => ({ args: v.args, keys: v.keys })),
      sampleRate: cfg.sampleRate, seed: cfg.seed, seconds: cfg.seconds, floorDb: cfg.floorDb,
    });
    const { pcm, places } = pack(r.clips, gap);
    const peak = Math.max(...r.clips.map((c) => c.peak));
    const file = path.join(outDir, `${e.name}.opus`);
    await encodeOpus(ffmpeg, pcm, cfg.sampleRate, cfg.kbps, file);
    const bytes = fs.readFileSync(file);
    const v = await w.run('verify', { bytes, ref: pcm, sampleRate: cfg.sampleRate, clips: places });
    const ok = v.lag === 0 && Math.abs(v.decodedLength - v.expectedLength) <= 1
      && v.snrDb >= MIN_SNR_DB && Math.abs(v.worstLevelDb) <= MAX_LEVEL_DB;
    if (!ok) failed++;
    if (peak > 1) loud++;

    const vars = {};
    e.variants.forEach((variant, vi) => {
      const takes = places.slice(vi * e.takes, (vi + 1) * e.takes).map((p) => [p.start, p.len]);
      for (const key of variant.keys) vars[key] = takes;
    });
    manifest.effects[e.name] = { file: `${e.name}.opus`, v: sha(bytes).slice(0, 10), src: e.src, vars };
    writeManifest(manifest, order); // after every effect, so an interrupted run keeps what finished

    console.log(`  ${e.name.padEnd(15)} ${String(places.length).padStart(3)} clip(s) ${fmtS(pcm.length / cfg.sampleRate).padStart(7)}`
      + ` ${fmtKB(bytes.length).padStart(9)} · SNR ${v.snrDb.toFixed(1)} dB, level ${v.worstLevelDb >= 0 ? '+' : ''}${v.worstLevelDb.toFixed(2)} dB`
      + ` · peak ${peak.toFixed(2)}`
      + (v.lag ? ` · OFFSET ${v.lag} samples` : '')
      + (v.decodedLength !== v.expectedLength ? ` · decodes to ${v.decodedLength - v.expectedLength > 0 ? '+' : ''}${v.decodedLength - v.expectedLength} samples` : '')
      + (ok ? '' : '  <-- CHECK FAILED'));
  }));

  let seconds = 0, bytes = 0;
  for (const n of order) {
    const entry = manifest.effects[n];
    if (!entry) continue;
    bytes += fs.statSync(path.join(outDir, entry.file)).size;
    const seen = new Set();
    for (const takes of Object.values(entry.vars)) {
      for (const [s, l] of takes) if (!seen.has(s)) { seen.add(s); seconds += l / manifest.sampleRate; }
    }
  }
  console.log(`\ndone in ${fmtS((Date.now() - t0) / 1000)} → ${OUT_DIR}/, ${path.relative(ROOT, MANIFEST)}`);
  console.log(`all effects: ${(bytes / 1048576).toFixed(2)} MB of Opus, ${seconds.toFixed(1)} s of audio`
    + ` (~${(seconds * 48000 * 4 / 1048576).toFixed(1)} MB once decoded at 48 kHz)`);
  if (loud) console.warn(`${loud} effect(s) peak above 0 dBFS (fine for float decoding, but check for harshness)`);
  if (failed) console.error(`${failed} file(s) failed the decode check (see above)`);
  return failed ? 1 : 0;
}

// Linux without a display (CI, ssh): Chromium's headless platform needs no X or Wayland
if (process.platform === 'linux' && !process.env.DISPLAY && !process.env.WAYLAND_DISPLAY) {
  app.commandLine.appendSwitch('ozone-platform', 'headless');
}
app.disableHardwareAcceleration();
app.setName('slopitaire-sfx');
app.setPath('userData', path.join(os.tmpdir(), 'slopitaire-sfx-renderer'));
app.on('window-all-closed', () => {});

app.whenReady()
  .then(main)
  .then((code) => app.exit(code), (err) => {
    console.error(`error: ${err.message}`);
    app.exit(1);
  });
